<?php
namespace App\Helpers;

class ReportGenerator {

    /**
     * Generates a self-contained HTML report with print CSS.
     * The user can Save as PDF from the browser (Ctrl+P).
     */
    public static function html($title, $kpis, $sections, $meta = []) {
        $now = date('F d, Y H:i');
        $org = 'Smart Agriculture Intelligence Platform (SAIP)';
        $footer = 'Generated by SAIP · Ministry of Agriculture and Animal Resources · ' . $now;

        $html = "<!DOCTYPE html><html><head><meta charset='utf-8'><title>" . htmlspecialchars($title) . "</title>";
        $html .= "<style>
            * { box-sizing: border-box; }
            body { font-family: 'Inter', Arial, sans-serif; background: #fff; color: #111; padding: 40px; max-width: 1000px; margin: auto; }
            h1 { color: #0F3D2E; margin: 0 0 4px; font-size: 28px; }
            .meta { color: #666; font-size: 12px; margin-bottom: 30px; }
            .kpi-grid { display: grid; grid-template-columns: repeat(auto-fit, minmax(160px, 1fr)); gap: 12px; margin: 20px 0; }
            .kpi { padding: 16px; border: 1px solid #e5e5e5; border-radius: 12px; background: #F5FBF7; }
            .kpi label { display: block; font-size: 11px; text-transform: uppercase; color: #666; letter-spacing: 0.5px; }
            .kpi strong { font-size: 22px; color: #16A34A; }
            h2 { color: #0F3D2E; margin-top: 32px; border-bottom: 2px solid #16A34A; padding-bottom: 6px; }
            table { width: 100%; border-collapse: collapse; margin-top: 12px; font-size: 13px; }
            th { background: #0F3D2E; color: white; padding: 10px; text-align: left; }
            td { padding: 10px; border-bottom: 1px solid #e5e5e5; }
            .footer { margin-top: 40px; font-size: 11px; color: #888; border-top: 1px solid #e5e5e5; padding-top: 12px; text-align: center; }
            .badge { display: inline-block; padding: 3px 8px; border-radius: 12px; font-size: 11px; font-weight: 600; }
            .badge.high { background: #FEE2E2; color: #991B1B; }
            .badge.medium { background: #FEF3C7; color: #92400E; }
            .badge.low { background: #D1FAE5; color: #065F46; }
            @media print { body { padding: 0; } h2 { page-break-after: avoid; } table { page-break-inside: auto; } }
        </style></head><body>";

        // Cover
        $html .= "<h1>" . htmlspecialchars($title) . "</h1>";
        $html .= "<div class='meta'>" . $org . " · " . $now . "</div>";

        // KPIs
        if (!empty($kpis)) {
            $html .= "<div class='kpi-grid'>";
            foreach ($kpis as $k => $v) {
                $html .= "<div class='kpi'><label>" . htmlspecialchars($k) . "</label><strong>" . htmlspecialchars($v) . "</strong></div>";
            }
            $html .= "</div>";
        }

        // Sections
        foreach ($sections as $section) {
            $html .= "<h2>" . htmlspecialchars($section['title']) . "</h2>";
            if (!empty($section['body'])) $html .= "<p>" . $section['body'] . "</p>";
            if (!empty($section['table'])) {
                $html .= "<table><thead><tr>";
                foreach ($section['table']['headers'] as $h) $html .= "<th>" . htmlspecialchars($h) . "</th>";
                $html .= "</tr></thead><tbody>";
                foreach ($section['table']['rows'] as $row) {
                    $html .= "<tr>";
                    foreach ($row as $cell) {
                        $html .= "<td>" . $cell . "</td>";
                    }
                    $html .= "</tr>";
                }
                $html .= "</tbody></table>";
            }
        }

        $html .= "<div class='footer'>" . $footer . "</div>";
        $html .= "<script>window.print();</script>";
        $html .= "</body></html>";

        return $html;
    }

    /**
     * Export array data as CSV.
     */
    public static function csv($filename, $headers, $rows) {
        header('Content-Type: text/csv; charset=utf-8');
        header('Content-Disposition: attachment; filename="' . $filename . '.csv"');
        $out = fopen('php://output', 'w');
        fputs($out, "\xEF\xBB\xBF"); // BOM for Excel
        fputcsv($out, $headers);
        foreach ($rows as $r) fputcsv($out, $r);
        fclose($out);
        exit;
    }

    /**
     * Export array as an Excel-compatible .xlsx — simple trick: HTML table with .xls extension.
     */
    public static function excel($filename, $title, $headers, $rows) {
        header('Content-Type: application/vnd.ms-excel; charset=utf-8');
        header('Content-Disposition: attachment; filename="' . $filename . '.xls"');
        echo '<html><head><meta charset="utf-8"></head><body>';
        echo '<h2>' . htmlspecialchars($title) . '</h2>';
        echo '<table border="1"><thead><tr>';
        foreach ($headers as $h) echo '<th>' . htmlspecialchars($h) . '</th>';
        echo '</tr></thead><tbody>';
        foreach ($rows as $r) {
            echo '<tr>';
            foreach ($r as $c) echo '<td>' . htmlspecialchars($c) . '</td>';
            echo '</tr>';
        }
        echo '</tbody></table></body></html>';
        exit;
    }
}
?>